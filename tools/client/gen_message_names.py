#!/usr/bin/env python3
"""
gen_message_names.py -- write dll/src/research_names.h from the game's own message class names.

The engine names each message class <Category><Name>Message, and both ids in a message's header
are djb2a hashes of names (MECMP src/game/runs.cpp; checked here: "PamSocialPlay" = 0x54776FC6,
"PamSocialPlayNamedChallengeFinishedMessage" = 0xD71D027F, "ServerPlayer" = 0xF3C93DD3). Where
the category ends inside a class name is not known, so every CamelCase prefix of every class
name is a candidate category. mec_ap.dll's research mode (dll/src/research.cpp) registers on all
of them and names what it hears from the type table.

Usage (read-only; the exe is only read):
    python tools/client/gen_message_names.py "<game folder>\\MirrorsEdgeCatalyst.exe"
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "dll" / "src" / "research_names.h"


def djb2a(s: str) -> int:
    h = 5381
    for c in s.encode():
        h = ((h * 33) ^ c) & 0xFFFFFFFF
    return h


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = Path(sys.argv[1]).read_bytes()
    names = sorted({m.decode() for m in re.findall(rb"(?<![A-Za-z0-9_])([A-Z][A-Za-z0-9]{2,80}Message)\x00", data)})
    cats: set[str] = set()
    for n in names:
        words = re.findall(r"[A-Z][a-z0-9]*|[A-Z]+(?![a-z])", n[: -len("Message")])
        for k in range(1, len(words)):
            cats.add("".join(words[:k]))
    known = {"PamSocialPlay": 0x54776FC6, "ServerPlayer": 0xF3C93DD3,
             "PamSocialPlayNamedChallengeFinishedMessage": 0xD71D027F}
    for k, v in known.items():
        assert djb2a(k) == v, k
    assert "PamSocialPlay" in cats and "ServerPlayer" in cats
    hashes = {djb2a(c) for c in cats}
    assert len(hashes) == len(cats), "two candidate categories share a hash"
    lines = [
        "#pragma once",
        "// Generated by tools/client/gen_message_names.py from the game's exe: do not edit.",
        f"// {len(names)} message class names; {len(cats)} candidate categories (every CamelCase prefix).",
        "#include <cstdint>",
        "namespace mecap::research {",
        "struct Name { uint32_t hash; const char* name; };",
        "constexpr Name kCategories[] = {",
        *[f'    {{0x{djb2a(c):08X}, "{c}"}},' for c in sorted(cats)],
        "};",
        "constexpr Name kTypes[] = {",
        *[f'    {{0x{djb2a(n):08X}, "{n}"}},' for n in names],
        "};",
        "} // namespace mecap::research",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(names)} types, {len(cats)} categories")


if __name__ == "__main__":
    main()
